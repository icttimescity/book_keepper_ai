-- Chạy file này MỘT LẦN trong Supabase Dashboard -> SQL Editor.
-- Tài khoản admin/admin vẫn nằm trong .env và không lưu ở bảng này.
-- Bảng này chỉ chứa các tài khoản quản lý bổ sung.

create table if not exists public.manager_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  display_name text not null,
  password_hash text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint manager_users_username_not_empty check (trim(username) <> ''),
  constraint manager_users_display_name_not_empty check (trim(display_name) <> '')
);

alter table public.manager_users enable row level security;

-- Không cho anon/authenticated đọc hoặc ghi danh sách tài khoản quản lý.
revoke all on table public.manager_users from anon, authenticated;

-- Backend dùng SUPABASE_SECRET_KEY để truy cập bảng này.
grant select, insert, update, delete on table public.manager_users to service_role;
grant usage, select on sequence public.manager_users_id_seq to service_role;

create index if not exists manager_users_username_idx
  on public.manager_users (username);
